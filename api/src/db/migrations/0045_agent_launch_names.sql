-- Launch names are fleet-wide leases; history never follows a reused name.
CREATE TABLE IF NOT EXISTS agent_name_pool (
  name_key VARCHAR(96) NOT NULL PRIMARY KEY,
  name VARCHAR(96) NOT NULL,
  current_session_id CHAR(36) NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS agent_name_leases (
  session_id CHAR(36) NOT NULL PRIMARY KEY,
  name_key VARCHAR(96) NOT NULL,
  name VARCHAR(96) NOT NULL,
  address_id CHAR(36) NOT NULL,
  started_at VARCHAR(100) NOT NULL,
  ended_at VARCHAR(100) NULL,
  cooldown_until VARCHAR(100) NULL,
  INDEX idx_agent_name_leases_name (name_key, started_at),
  INDEX idx_agent_name_leases_address (address_id, started_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

